<script type="text/javascript">
  $(document).ready(function() {
    $(".hindi-key-modalpad-review table tr td a").bind("click", function(e) {
      e.stopPropagation();
      
      var idname = $("#overlayDiv_modal").attr("data-value");
      
      var key_modal = $(this).attr("data-value");
      e.preventDefault();
      
      prev_text = $("#" + idname).val();
      if (typeof key_modal !== "undefined") {
        if (key_modal === "clear") {
          $("#" + idname).val("").trigger("change");
        } else if (key_modal === "backspace") {
          $("#" + idname).val(prev_text.substr(0, prev_text.length - 1)).trigger("change");
          if ($("#" + idname).val() === "") {
            $(".hindi-key-modalpad-review table tr td a[data-value=clear]").trigger("click");
          }
        } else {
          if (prev_text.length < 70) {
            
            $("#" + idname).val(prev_text + key_modal).trigger("change");
            
            var formData = {
              'key-modalword': prev_text + key_modal,
            };
          }
        }
      } else {
        alert("Unable to fill search box!");
      }
    });

  });
  $(document).ready(function() {
    $('.search-box-nok').click(function(e) {
      e.stopPropagation();
      var id = $(this).attr('id');
      $("#overlayDiv_modal").show();
      $("#overlayDiv_modal").attr("data-value", id);
    });
    $('#close').click(function() {
      $("#overlayDiv_modal").hide();
    });
  });
  $(document).click(function() {
    $("#overlayDiv_modal").hide();
  });
</script>
