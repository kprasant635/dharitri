    // function to get settlemnet basic details 
    public function getSettlementBasicDetails($app_no)
    {
        $query = $this->db->query("SELECT * FROM settlement_basic WHERE status=? AND applid=?", array('N', $app_no));
        if($query->num_rows() == 0){
            return "No Data Found";
        }else{
            return $result = $query->row();
        }
    }

